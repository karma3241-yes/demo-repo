// Builds a map of the game's source: every top-level function/const per file, where each is used, and which files
// depend on which. Run: node tools/codegraph.mjs  →  docs/CODEGRAPH.md (read/grep it) + docs/codegraph.json (for tools)
import { readFileSync, readdirSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
const SRC = new URL('../src/', import.meta.url), OUT = new URL('../docs/', import.meta.url);
const files = readdirSync(SRC).filter(f => f.endsWith('.js')).sort(); // build order = name order (tools/build.mjs)
const text = {}, lines = {};
for (const f of files) { text[f] = readFileSync(new URL(f, SRC), 'utf8'); lines[f] = text[f].split('\n'); }

// top-level declarations only (column 0), which is how every shared name in this one-closure codebase is made
const DECL = /^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)|^(?:const|let|var)\s+([A-Za-z_$][\w$]*(?:\s*=[^,;]*)?(?:\s*,\s*[A-Za-z_$][\w$]*(?:\s*=[^,;]*)?)*)/;
const syms = Object.create(null); // name -> {file,line,kind,usedBy:{file:count}}
for (const f of files) lines[f].forEach((ln, i) => {
  const m = DECL.exec(ln); if (!m) return;
  if (m[1]) { syms[m[1]] ??= { file: f, line: i + 1, kind: 'fn', usedBy: {} }; return; }
  // const a=1,b=2 / const {x}= is skipped; take every simple name before '=' at depth 0
  const head = ln.replace(/^(?:const|let|var)\s+/, ''); let depth = 0, cur = '', names = [], inName = true;
  for (const ch of head) {
    if ('([{'.includes(ch)) depth++; else if (')]}'.includes(ch)) depth--;
    if (depth === 0 && ch === ',') { inName = true; cur = ''; continue; }
    if (depth === 0 && ch === ';') break;
    if (inName) { if (/[\w$]/.test(ch)) cur += ch; else if (cur) { names.push(cur); inName = false; cur = ''; } }
  }
  if (inName && cur) names.push(cur);
  for (const n of names) if (/^[A-Za-z_$][\w$]*$/.test(n)) syms[n] ??= { file: f, line: i + 1, kind: /=\s*(\([^)]*\)|[\w$]+)\s*=>/.test(ln) ? 'fn' : 'const', usedBy: {} };
});

// references: whole-word hits outside the defining line, per file (strings/comments included; good enough to navigate)
const names = Object.keys(syms).filter(n => n.length > 2);
const edges = {}; // fileA -> fileB -> count (A uses something defined in B)
for (const f of files) {
  const words = text[f].match(/[A-Za-z_$][\w$]*/g) || [], cnt = Object.create(null);
  for (const w of words) if (syms[w]) cnt[w] = (cnt[w] || 0) + 1;
  for (const [w, c] of Object.entries(cnt)) {
    const s = syms[w], own = s.file === f ? c - 1 : c; if (own <= 0 || w.length <= 2) continue;
    s.usedBy[f] = own; if (s.file !== f) { (edges[f] ??= {})[s.file] = (edges[f][s.file] || 0) + own; }
  }
}

const purpose = f => { for (const ln of lines[f].slice(0, 6)) { const m = /^\/\/\s*(?:=+\s*)?(.+)/.exec(ln); if (m && !/^=+$/.test(m[1].trim())) return m[1].trim().slice(0, 110); } return ''; };
const kb = f => (statSync(new URL(f, SRC)).size / 1024).toFixed(1);
mkdirSync(OUT, { recursive: true });

let md = `# Code graph\n\nGenerated by \`node tools/codegraph.mjs\` — re-run after big changes. ${files.length} files, ${Object.keys(syms).length} top-level names.\n` +
  `All src/*.js files are concatenated in this order into ONE scope (tools/build.mjs), so any top-level name is visible everywhere after it loads.\n` +
  `Find a name: search this file for \`### name\` or \`\\bname\\b\`. Each entry: where it's defined → which files use it (hit counts).\n\n## Files (build order)\n\n| File | KB | Lines | Names | Uses most from | Purpose |\n|---|---|---|---|---|---|\n`;
for (const f of files) {
  const n = Object.values(syms).filter(s => s.file === f).length;
  const top = Object.entries(edges[f] || {}).sort((a, b) => b[1] - a[1]).slice(0, 3).map(([g]) => g.replace('.js', '')).join(', ');
  md += `| ${f} | ${kb(f)} | ${lines[f].length} | ${n} | ${top} | ${purpose(f).replace(/\|/g, '/')} |\n`;
}
// file dependency diagram: strongest edges only so it stays readable
const flat = []; for (const [a, m] of Object.entries(edges)) for (const [b, c] of Object.entries(m)) flat.push([a, b, c]);
flat.sort((x, y) => y[2] - x[2]);
const id = f => 'f' + f.replace(/[^\w]/g, '_');
md += `\n## Who depends on whom (strongest 70 links)\n\n\`\`\`mermaid\ngraph LR\n` + flat.slice(0, 70).map(([a, b, c]) => `  ${id(a)}["${a.replace('.js', '')}"] -->|${c}| ${id(b)}["${b.replace('.js', '')}"]`).join('\n') + '\n```\n';
md += `\n## Names by file\n`;
for (const f of files) {
  const own = Object.entries(syms).filter(([, s]) => s.file === f).sort((a, b) => a[1].line - b[1].line);
  if (!own.length) continue;
  md += `\n### ${f}\n\n`;
  for (const [n, s] of own) {
    const used = Object.entries(s.usedBy).filter(([g]) => g !== f).sort((a, b) => b[1] - a[1]);
    md += `- \`${n}\` (${s.kind}) [${f}:${s.line}](../src/${f}#L${s.line})` + (used.length ? ` ← ${used.slice(0, 8).map(([g, c]) => g.replace('.js', '') + '×' + c).join(', ')}${used.length > 8 ? ` +${used.length - 8} more` : ''}` : n.length <= 2 ? ' (short name, uses not tracked)' : s.usedBy[f] ? ' (this file only)' : ' (unused?)') + '\n';
  }
}
writeFileSync(new URL('CODEGRAPH.md', OUT), md);
writeFileSync(new URL('codegraph.json', OUT), JSON.stringify({ files: Object.fromEntries(files.map(f => [f, { kb: +kb(f), lines: lines[f].length, purpose: purpose(f), uses: edges[f] || {} }])), symbols: syms }, null, 1));
console.log(`docs/CODEGRAPH.md + docs/codegraph.json: ${files.length} files, ${Object.keys(syms).length} names, ${flat.length} file links`);
